"""Build browser catalog from audited nutrients and dated shopping offers."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
audit = json.loads((root / 'data/product-verification-2026-10-15.json').read_text())
shopping = json.loads((root / 'data/shopping-offers.json').read_text())
offers = {x['product_id']: x for x in shopping['offers']}
rows = []
for p in audit['products']:
    n = p['nutrition_per_100ml']
    rows.append(dict(id=p['id'], name=p.get('name', p['baseline']['name']), cal=n['energy_kcal'], sugar=n['total_sugars_g'], fat=n['saturated_fat_g'], totalFat=n['total_fat_g'], transFat=n['trans_fat_g'], transFatBound=p.get('nutrition_bounds_per_100ml', {}).get('trans_fat_g'), protein=n['protein_g'], calcium=n['calcium_mg'], lacto=p['id'] in ['comfort','sokpyun','digest'], basis='100mL', offer=offers[p['id']], sourceIds=p['source_ids']))
(root / 'catalog.js').write_text('// Generated by scripts/build_catalog.py; edit source JSON.\nconst DB = ' + json.dumps(rows, ensure_ascii=False, indent=2) + ';\n')
